"""Ambient Scribe — turns an exam conversation into a draft chart.

The clinical contract (CONTEXT.md — "Grounding over generation"): the scribe
produces a DRAFT for practitioner review and never a final note. The draft
lands on the encounter document as:

    scribe_draft: {
        status: 'draft' | 'reviewed',
        sections: {subjective, objective, assessment, plan},
        model, generatedAt, reviewedBy?, reviewedAt?
    }

Drafts are generated by the agent tool `draft_encounter_chart`, by this
module's CLI (`python -m gozvision_agent.scribe <encounter_id>`), or by the
library functions below. Only a practitioner moves a draft to 'reviewed'
(the clinic app writes that transition; Firestore rules gate it).
"""
import re
from datetime import datetime, timezone

import os

try:
    import firebase_admin
    from firebase_admin import firestore as fb_firestore

    if not firebase_admin._apps:
        firebase_admin.initialize_app()
    _db = fb_firestore.client()
    FIREBASE_AVAILABLE = True
except Exception as _e:  # pragma: no cover - exercised in stub environments
    _db = None
    FIREBASE_AVAILABLE = False

try:
    import google.genai as genai
except Exception:  # pragma: no cover
    genai = None

_SCRIBE_MODEL = os.environ.get("GOZVISION_SCRIBE_MODEL", "gemini-2.5-flash")

_SECTIONS = ("subjective", "objective", "assessment", "plan")


def build_chart_prompt(transcript: str, patient_context: str = "") -> str:
    """Builds the charting prompt. Pure — unit-testable."""
    context_line = f"\nPatient context: {patient_context}" if patient_context else ""
    return f"""You are an optometric scribe. Convert the examination conversation below
into a draft SOAP note for the treating optometrist to review and edit.

Rules:
- Record only what the conversation supports; where information is missing,
  write "[not documented]" rather than inventing findings.
- Never diagnose or add recommendations beyond what was discussed.
- Use standard optometric terminology and abbreviations.
- Keep each section concise (3-6 bullet lines).{context_line}

Conversation:
\"\"\"
{transcript.strip()}
\"\"\"

Output exactly these four sections, each starting with its heading on its
own line: SUBJECTIVE:, OBJECTIVE:, ASSESSMENT:, PLAN:"""


def parse_chart(response_text: str) -> dict:
    """Parses the model output into the four SOAP sections. Pure — testable."""
    sections = {name: "" for name in _SECTIONS}
    positions = []
    for name in _SECTIONS:
        m = re.search(rf"^{name.upper()}\s*:\s*$|^{name.upper()}\s*:\s*(.+)$",
                      response_text, re.MULTILINE | re.IGNORECASE)
        if m:
            positions.append((name, m.start(), m.end(), m.group(1)))
    positions.sort(key=lambda p: p[1])
    for i, (name, start, end, inline) in enumerate(positions):
        body_end = positions[i + 1][1] if i + 1 < len(positions) else len(response_text)
        body = (inline or "") + response_text[end:body_end]
        sections[name] = body.strip().strip(":").strip()
    return sections


async def draft_chart(encounter_id: str, transcript: str | None = None) -> dict:
    """Generates and persists a scribe draft for one encounter.

    With Firebase configured, `transcript` may be omitted — the encounter
    document's `transcript_text` field is used. Returns the stored draft
    (or an error-shaped dict in stub mode) so the agent tool can relay it.
    """
    encounter = None
    if FIREBASE_AVAILABLE and _db is not None:
        snap = _db.collection("encounters").document(encounter_id).get()
        if snap.exists:
            encounter = snap.to_dict()
    transcript = transcript or (encounter or {}).get("transcript_text") or ""
    if not transcript.strip():
        return {
            "status": "error",
            "message": "No transcript available for this encounter. "
                       "Provide one or record it on the encounter document.",
        }

    api_key = os.environ.get("GEMINI_API_KEY")
    if genai is None or not api_key:
        return {"status": "error",
                "message": "Scribe model unavailable (missing GEMINI_API_KEY or SDK)."}

    client = genai.Client(api_key=api_key)
    patient_context = ""
    if encounter:
        patient_context = f"encounter type: {encounter.get('type', 'exam')}"
    response = client.models.generate_content(
        model=_SCRIBE_MODEL,
        contents=build_chart_prompt(transcript, patient_context),
    )
    sections = parse_chart(response.text or "")

    draft = {
        "status": "draft",
        "sections": sections,
        "model": _SCRIBE_MODEL,
        "generatedAt": datetime.now(timezone.utc).isoformat(),
    }
    if FIREBASE_AVAILABLE and _db is not None:
        _db.collection("encounters").document(encounter_id).set(
            {"scribe_draft": draft}, merge=True
        )
    return {"status": "drafted", "encounter_id": encounter_id, **draft}
